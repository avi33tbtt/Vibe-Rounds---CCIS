// Dev-time only. Compiles ccis/schemas/*.json to committed standalone ES-module validators (D-005).
// Not imported by the app. Usage: node scripts/build-validators.js [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = { manifest: 'manifest', element: 'element', elementGroup: 'element-group', terminologyBinding: 'terminology-binding', decisionNode: 'decision-node', pathway: 'pathway', analytics: 'analytics', executionManifest: 'execution-manifest', contextEnvelope: 'context-envelope', importReport: 'import-report', validationRecord: 'validation-record', runResult: 'run-result', runRecord: 'run-record' };
const out = join(root, 'ccis', 'validators', 'ccis-validators.js');

const ajv = new Ajv2020({ allErrors: true, strict: true, strictRequired: false, code: { source: true, esm: true } });
const ids = {};
for (const [exportName, file] of Object.entries(names)) {
  const schema = JSON.parse(readFileSync(join(root, 'ccis', 'schemas', `${file}.schema.json`), 'utf8'));
  ajv.addSchema(schema);
  ids[exportName] = schema.$id;
}
const code = '// GENERATED by scripts/build-validators.js. Do not edit.\n' + standaloneCode(ajv, ids) + '\n';

if (process.argv.includes('--check')) {
  const same = existsSync(out) && readFileSync(out, 'utf8') === code;
  if (!same) { console.error('ccis/validators/ccis-validators.js is out of date. Run: npm run build'); process.exit(1); }
} else {
  writeFileSync(out, code);
  console.log('wrote', out);
}
